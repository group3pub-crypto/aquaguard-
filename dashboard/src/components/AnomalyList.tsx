import { fmtNumber, fmtPercent, fmtTime, humanize, severityTone } from '@/lib/format';
import type { Anomaly, TopFactor } from '@/lib/types';
import { StatusBadge } from './StatusBadge';

const GENERATED_BY: Record<string, string> = {
  shap_tree_explainer: 'SHAP values from the ML classifier',
  rule_heuristic: 'rule-based heuristic (not ML)',
};

function factorText(f: TopFactor): string {
  const bits: string[] = [];
  if (typeof f.value === 'number') bits.push(`value ${fmtNumber(f.value, 2)}`);
  if (typeof f.shap === 'number') bits.push(`SHAP ${f.shap >= 0 ? '+' : ''}${fmtNumber(f.shap, 3)}`);
  if (typeof f.note === 'string' && f.note) bits.push(f.note);
  return bits.join(' · ');
}

/** Shows the explanation exactly as the backend produced it, labelled with `generated_by`. */
export function AnomalyList({ anomalies }: { anomalies: Anomaly[] }) {
  return (
    <ul className="space-y-4">
      {anomalies.map((a) => {
        const ex = a.explanation;
        const factors = Array.isArray(ex?.top_factors)
          ? ex.top_factors.filter((f): f is TopFactor => typeof f === 'object' && f !== null)
          : [];
        const gen = typeof ex?.generated_by === 'string' ? ex.generated_by : null;
        return (
          <li key={String(a.id)} className="rounded-lg border border-line p-4">
            <div className="flex flex-wrap items-center gap-2">
              <span className="font-semibold">{humanize(a.anomaly_type ?? 'unknown')}</span>
              <StatusBadge tone={severityTone(a.severity)}>Severity {fmtPercent(a.severity)}</StatusBadge>
              <StatusBadge tone={a.resolved_at ? 'safe' : 'error'}>{a.resolved_at ? 'Resolved' : 'Ongoing'}</StatusBadge>
            </div>
            <p className="mt-1 text-xs text-ink-2">
              Detected {fmtTime(a.detected_at)} · Confidence {fmtPercent(a.confidence)} · Est. loss {fmtNumber(a.est_loss_lpm)} L/min
            </p>
            {ex && (factors.length > 0 || gen) ? (
              <div className="mt-3">
                {factors.length > 0 ? (
                  <ul className="list-disc space-y-1 pl-5 text-sm">
                    {factors.map((f, i) => (
                      <li key={`${f.feature ?? 'factor'}-${i}`}>
                        <span className="font-semibold">{f.feature ? humanize(f.feature) : 'Factor'}:</span> {factorText(f) || 'no detail'}
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p className="text-sm text-ink-2">No contributing factors were recorded.</p>
                )}
                <p className="mt-2 text-xs text-ink-2">
                  Explanation generated by: {gen ? (GENERATED_BY[gen] ?? gen) : 'unknown'}
                  {ex.classifier ? ` · classifier: ${ex.classifier}` : ''}
                  {typeof ex.iso_score === 'number' ? ` · isolation score ${fmtNumber(ex.iso_score, 2)}` : ''}
                </p>
              </div>
            ) : (
              <p className="mt-3 text-sm text-ink-2">No explanation available for this anomaly.</p>
            )}
          </li>
        );
      })}
    </ul>
  );
}
