import { fmtNumber, fmtTime, humanize, severityTone } from '@/lib/format';
import type { Anomaly } from '@/lib/types';
import { StatusBadge } from './StatusBadge';

/** Shows the explanation exactly as the backend produced it, labelled with `generated_by`. */
export function AnomalyList({ anomalies }: { anomalies: Anomaly[] }) {
  return (
    <ul className="space-y-4">
      {anomalies.map((a) => (
        <li key={String(a.id)} className="rounded-lg border border-line p-4">
          <div className="flex flex-wrap items-center gap-2">
            <span className="font-semibold">{humanize(a.anomaly_type)}</span>
            <StatusBadge tone={severityTone(a.severity)}>Severity {String(a.severity)}</StatusBadge>
            <StatusBadge tone={a.resolved_at ? 'safe' : 'error'}>{a.resolved_at ? 'Resolved' : 'Ongoing'}</StatusBadge>
          </div>
          <p className="mt-1 text-xs text-ink-2">
            Detected {fmtTime(a.detected_at)} · Confidence {fmtNumber(a.confidence * 100, 0)}% · Est. loss {fmtNumber(a.est_loss_lpm)} L/min
          </p>
          {a.explanation && a.explanation.reasons.length > 0 ? (
            <div className="mt-3">
              <ul className="list-disc space-y-1 pl-5 text-sm">
                {a.explanation.reasons.map((r, i) => (
                  <li key={`${r.feature}-${i}`}>
                    <span className="font-semibold">{r.feature}:</span> {r.text}
                  </li>
                ))}
              </ul>
              <p className="mt-2 text-xs text-ink-2">Explanation generated by: {a.explanation.generated_by}</p>
            </div>
          ) : (
            <p className="mt-3 text-sm text-ink-2">No explanation available for this anomaly.</p>
          )}
        </li>
      ))}
    </ul>
  );
}
